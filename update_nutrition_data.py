import pandas as pd
from nutrition_analyzer import ThaiNutritionAnalyzer
import os

def update_nutrition_data():
    """อัพเดทข้อมูลคุณค่าทางโภชนาการในไฟล์ CSV"""
    
    # ตรวจสอบว่ามีไฟล์ CSV หรือไม่
    csv_path = "thai_food_processed.csv"
    if not os.path.exists(csv_path):
        print(f"ไม่พบไฟล์ {csv_path}")
        return
    
    # โหลดข้อมูล
    print("กำลังโหลดข้อมูล...")
    df = pd.read_csv(csv_path)
    
    # สร้าง NutritionAnalyzer
    analyzer = ThaiNutritionAnalyzer()
    
    # เพิ่มคอลัมน์คุณค่าทางโภชนาการถ้ายังไม่มี
    if 'nutrition_info' not in df.columns:
        df['nutrition_info'] = ''
    
    # วิเคราะห์คุณค่าทางโภชนาการสำหรับแต่ละเมนู
    print(f"กำลังวิเคราะห์คุณค่าทางโภชนาการสำหรับ {len(df)} เมนู...")
    
    for idx, row in df.iterrows():
        print(f"กำลังประมวลผล: {row['name']} ({idx+1}/{len(df)})")
        
        # วิเคราะห์คุณค่าทางโภชนาการ
        nutrition_data = analyzer.analyze_recipe_nutrition(row['ingredient'])
        
        # สร้างข้อความสรุป
        nutrition_summary = analyzer.get_nutrition_summary(nutrition_data)
        
        # บันทึกลงใน DataFrame
        df.at[idx, 'nutrition_info'] = nutrition_summary
    
    # บันทึกกลับไปยังไฟล์ CSV
    df.to_csv(csv_path, index=False)
    print(f"✅ อัพเดทข้อมูลคุณค่าทางโภชนาการเรียบร้อยแล้ว!")
    
    # แสดงตัวอย่างข้อมูล
    print("\nตัวอย่างข้อมูลที่อัพเดท:")
    print(df[['name', 'nutrition_info']].head(3))
    
    # ลบไฟล์ embeddings เก่าเพื่อให้สร้างใหม่
    embeddings_files = ['embeddings.pkl', 'nutrition_embeddings.pkl']
    for file in embeddings_files:
        if os.path.exists(file):
            os.remove(file)
            print(f"ลบไฟล์ {file} เรียบร้อยแล้ว")
    
    print("\n💡 หมายเหตุ: ระบบจะสร้าง embeddings ใหม่ในครั้งถัดไปที่เปิดแอป")

